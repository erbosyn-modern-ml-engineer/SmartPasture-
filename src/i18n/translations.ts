function siteSummary(site: SiteDetail, language: Language): string {
  if (site.actionId === 'INSPECT_FIRST') {
    return pick({
      kk: `${site.title} алғашқы тексеріс үшін мықты кандидат: басымдығы жоғары, тәуекелі төмен, сенімділігі жақсы.`,
      ru: `${site.title} — сильный кандидат для первой проверки: высокий приоритет, низкий риск и высокая уверенность.`,
      en: `${site.title} is a strong first-inspection candidate: high priority, low risk, and good confidence.`,
    }, language, site.summary)
  }
  if (site.actionId === 'NOT_RECOMMENDED_CURRENT_EVIDENCE') {
    return pick({
      kk: `${site.title} қолдағы дерек бойынша алғашқы қысқа тізімге кірмейді.`,
      ru: `${site.title} по текущим данным не входит в первый короткий список.`,
      en: `${site.title} does not enter the first shortlist on current evidence.`,
    }, language, site.summary)
  }
  return pick({
    kk: `${site.title} қысқа тізім үшін пайдалы, бірақ ${pick(actionSummaryCopy[site.actionId], language)}.`,
    ru: `${site.title} полезен для короткого списка, но ${pick(actionSummaryCopy[site.actionId], language).toLowerCase()}.`,
    en: `${site.title} is useful for the shortlist, but ${pick(actionSummaryCopy[site.actionId], language).toLowerCase()}.`,
  }, language, site.summary)
}

function sitePositiveReasons(site: SiteDetail, language: Language): string[] {
  const texts: string[] = []
  if (site.priorityScore >= 0.65) texts.push(pick({ kk: 'Басымдық бағасы алғашқы толқынға жеткілікті.', ru: 'Оценка приоритета достаточно сильная для первой волны.', en: 'Priority score is strong enough for the first wave.' }, language))
  if (site.scores.hps >= 0.7) texts.push(pick({ kk: 'HPS су потенциалы бойынша жақсы сигнал береді.', ru: 'HPS даёт хороший сигнал по водному потенциалу.', en: 'HPS gives a good water-potential signal.' }, language))
  if (site.riskBand === 'low') texts.push(pick({ kk: 'Тәуекел төмен, сондықтан далалық тексеріс қауіпсізірек.', ru: 'Риск низкий, поэтому полевую проверку проводить безопаснее.', en: 'Risk is low, so the field check is safer.' }, language))
  if (site.confidenceBand === 'high') texts.push(pick({ kk: 'Сенімділік жоғары, сигналдар тұрақты көрінеді.', ru: 'Уверенность высокая, сигналы выглядят устойчиво.', en: 'Confidence is high and signals look stable.' }, language))
  return texts.length ? texts.slice(0, 3) : site.positiveReasons
}

function siteCautionReasons(site: SiteDetail, language: Language): string[] {
  const texts: string[] = []
  if (site.riskBand !== 'low') texts.push(pick({ kk: 'Тәуекел шешім алдында қосымша тексеруді талап етеді.', ru: 'Риск требует дополнительной проверки перед решением.', en: 'Risk requires additional verification before a decision.' }, language))
  if (site.confidenceBand !== 'high') texts.push(pick({ kk: 'Сенімділік шектеулі: жанама немесе архив деректерін нақтылау керек.', ru: 'Уверенность ограничена: косвенные или архивные данные нужно уточнить.', en: 'Confidence is not complete: proxy or archive data needs clarification.' }, language))
  if (site.actionId === 'HUMAN_REVIEW_REQUIRED') texts.push(pick({ kk: 'Сарапшы тексерісінсіз әрекет қабылдамаңыз.', ru: 'Не принимайте действие без экспертной проверки.', en: 'Do not take action without human review.' }, language))
  if (site.actionId === 'DEFER' || site.actionId === 'NOT_RECOMMENDED_CURRENT_EVIDENCE') texts.push(pick({ kk: 'Алғашқы тексеріс лимитіне қоспаған дұрыс.', ru: 'Лучше не включать в лимит первой проверки.', en: 'Best excluded from the first inspection limit.' }, language))
  return texts.length ? texts.slice(0, 3) : site.cautionReasons
}

